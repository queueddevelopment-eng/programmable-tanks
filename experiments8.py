def make_cfg(vk, walls, pits, seed):
    deck = dict(E7.V04)
    for c in E7.SPECIALS: deck[c] = deck.get(c, 0) + 1
    base = dict(deck=deck, cooldown=1, build_behind=True, hunt_avoid=True, walls=walls, pits=pits,
                shot_clock=10, clock_roles=True, clock_leader=True, clock_cards=True, clock_first=seed % 2)
    base.update(VARIANTS[vk][1])
    return Config(**base)

def overtime_ticks(tr, clock, armor=5):
    """Rebuild the shot-clock state per tick from a trace (armor changes only; a hit fully soaked by a
    shield also resets the engine's clock, so the rebuilt count is checked against play()['overtime'])."""
    out, last, prev = [], 0, (0, 0, 0, 0, 0, armor, 0, 0, armor)
    for row in tr:
        out.append(row[0] - 1 - last >= clock)
        if row[5] != prev[5] or row[8] != prev[8]: last = row[0]
        prev = row
    return out

def stretches(ot):
    """Index lists of each contiguous run of overtime ticks."""
    out, cur = [], []
    for i, x in enumerate(ot):
        if x: cur.append(i)
        elif cur: out.append(cur); cur = []
    if cur: out.append(cur)
    return out

def attacker_of(tr, idx, path=False):
    """The attacking seat in one overtime stretch, read from the actions: the holder only ever plays
    FIRE or TRACK (or IDLE while stunned); the attacker HUNTs, or under the 8-card program turns RIGHT or drives
    FWD; under clock_path it drives its own route. None if the stretch does not tell."""
    for s, ai in ((0, 1), (1, 2)):
        acts = {tr[i][ai] for i in idx}
        if TRACK in acts: continue
        if acts & {HUNT, RIGHT, FWD} or (path and acts - {FIRE, IDLE}): return s
    return None

def analyse(tr, r, cfg, attack8):
    """Rule-fired numbers for one round from its trace."""
    w = cfg.size + 2
    xy = lambda p: (p % w - 1, p // w - 1)
    ot = overtime_ticks(tr, cfg.shot_clock, cfg.armor)
    pits = set(cfg.pits)
    starts = (xy(1 * w + 1), xy(cfg.size * w + cfg.size))
    ot_falls = att_ticks = blk_right = blk_fwd = 0
    for i, row in enumerate(tr):
        for s, pi in ((0, 3), (1, 6)):
            prev = xy(tr[i - 1][pi]) if i else starts[s]
            if xy(row[pi]) != prev and xy(row[pi]) in pits and ot[i]: ot_falls += 1
    if attack8:
        for idx in stretches(ot):
            s = attacker_of(tr, idx)
            if s is None: continue
            acts = [tr[i][1 + s] for i in idx]
            att_ticks += len(acts); blk_right += acts.count(RIGHT); blk_fwd += acts.count(FWD)
    return dict(ot_check=sum(ot) == r["overtime"], ot_falls=ot_falls, att_ticks=att_ticks, blk_right=blk_right, blk_fwd=blk_fwd, ot=ot)

def stuck_detail(tr, ot, cfg, inner):
    """For a stuck round: where the attacker spent the quiet overtime stretch."""
    w = cfg.size + 2
    xy = lambda p: (p % w - 1, p // w - 1)
    last = 0
    for i, row in enumerate(tr):
        if i and (row[5] != tr[i - 1][5] or row[8] != tr[i - 1][8]): last = row[0]
    idx = [i for i, row in enumerate(tr) if row[0] > last and ot[i]]
    att = attacker_of(tr, idx, cfg.clock_path) if idx else None
    if att is None: return dict(att=None, near=False, any=False, squares=0, path=[])
    pi = 3 if att == 0 else 6
    sq = [xy(tr[i][pi]) for i in idx]
    near = lambda p: any(max(abs(p[0] - q[0]), abs(p[1] - q[1])) <= 1 for q in inner)
    k = sum(near(p) for p in sq)
    return dict(att=att, near=k * 2 >= len(sq), any=k > 0, squares=len(set(sq)), path=sq[-12:])

def one_job(args):
    bname, li, k, vks = args
    seed = li * 10**5 + k
    walls, pits = LAYOUTS[bname]
    kind = ("EvE", "EvN", "NvN", "EvE", "NvE", "NvN")[k % 6]
    skills = {"EvE": ("expert", "expert"), "EvN": ("expert", "novice"), "NvE": ("novice", "expert"), "NvN": ("novice", "novice")}[kind]
    rng = random.Random(seed)
    cfg0 = make_cfg("A", walls, pits, seed); grid = cfg0.grid()
    brng = random.Random(77)                                   # the same bench and sparring set as experiments7
    bcfg = Config(deck=dict(E7.V04), cooldown=1, build_behind=True, hunt_avoid=True)
    bench = X.STARTERS + [flat(rand_program(brng, bcfg)) for _ in range(4)]
    spar = [flat(rand_program(brng, bcfg)) for _ in range(4)]
    pile = shared_deck(E7.V04) + list(E7.SPECIALS); rng.shuffle(pile)
    hands = [[pile.pop() for _ in range(X.HAND)] for _ in (0, 1)]
    progs = []
    for s in (0, 1):                                           # built once, shared by every variant (the cache)
        avail = {c: CHASSIS.get(c, 0) + hands[s].count(c) for c in cfg0.deck}
        p, q = X.build(rng, avail, cfg0, grid, bench, spar, skills[s])
        progs.append(p)
        left = Counter(hands[s])
        for c, n in Counter(p).items(): left[c] -= max(0, n - CHASSIS.get(c, 0))
        hands[s] = [c for c, n in left.items() for _ in range(max(0, n))]
    inner = pockets(walls, pits)[0]
    out = {}
    for vk in vks:
        cfg = make_cfg(vk, walls, pits, seed)
        r, tr, stops = E7.stops_dynamic(random.Random(seed ^ 0x5EED00), list(progs), [list(h) for h in hands], list(pile),
                                        cfg, grid, skills, X.STOPS, None)
        st = E7.stall_info(tr, cfg.shot_clock)
        an = analyse(tr, r, cfg, cfg.clock_attack == ATTACK_8 and cfg.clock_cards)
        o = dict(r=r, stall=st, sig=hash(tuple(tr)), progs=[show(p) for p in progs],
                 ot_check=an["ot_check"], ot_falls=an["ot_falls"],
                 att_ticks=an["att_ticks"], blk_right=an["blk_right"], blk_fwd=an["blk_fwd"])
        if st: o["where"] = stuck_detail(tr, an["ot"], cfg, inner)
        out[vk] = o
    return bname, kind, seed, out

# ---------------------------------------------------------------- report
def score_layout(rows):
    """Per-layout scorer (reused by E5): rows = [(kind, result_dict)] for one layout and variant."""
    n = len(rows); st = sum(o["stall"] is not None for k, o in rows)
    dec = [o for k, o in rows if k in ("EvE", "NvN") and o["r"]["winner"] is not None]
    return dict(n=n, stuck=st, kills=sum(o["r"]["kill"] for k, o in rows), draws=sum(o["r"]["winner"] is None for k, o in rows),
                seat_a=sum(o["r"]["winner"] == 0 for o in dec), seat_dec=len(dec), flagged=st >= FLAG)

def pct(a, b): return f"{a / b:.0%}" if b else "-"

def report(vk, res):
    rows = [(b, k, out[vk]) for (b, k, s, out) in res if vk in out]
    print(f"\n=== {vk}. {VARIANTS[vk][0]} ===")
    print(f"{'layout':20} {'pockets':>8} {'stuck':>9} {'flag':>5} {'kills':>6} {'draws':>6} {'seat A':>9}")
    for b in LAYOUTS:
        rs = [(k, o) for (bb, k, o) in rows if bb == b]
        if not rs: continue
        sc = score_layout(rs); inn, edg = pockets(*LAYOUTS[b])
        print(f"{b:20} {len(inn):>3} / {len(edg):<3} {sc['stuck']:>2}/{sc['n']:<2} {sc['stuck']/sc['n']:>4.0%} {'FLAG' if sc['flagged'] else '':>5}"
              f" {sc['kills']/sc['n']:>6.0%} {sc['draws']/sc['n']:>6.0%} {pct(sc['seat_a'], sc['seat_dec']):>5} ({sc['seat_dec']})")
    for lab, grp in (("named", NAMED), ("generated", GEN), ("ALL", list(LAYOUTS))):
        rs = [(k, o) for (b, k, o) in rows if b in grp]
        if not rs: continue
        sc = score_layout(rs)
        print(f"{lab:20} {'':>9} {sc['stuck']:>2}/{sc['n']:<3}{sc['stuck']/sc['n']:>4.0%} {'':>5} {sc['kills']/sc['n']:>6.0%} {sc['draws']/sc['n']:>6.0%}"
              f" {pct(sc['seat_a'], sc['seat_dec']):>5} ({sc['seat_dec']})")
    allo = [o for (b, k, o) in rows]; n = len(allo)
    for kind, lab in (("EvE", "EvE"), ("mix", "EvN/NvE"), ("NvN", "NvN")):
        rs = [o for (b, k, o) in rows if k == kind or (kind == "mix" and k in ("EvN", "NvE"))]
        if rs: print(f"   {lab}: stuck {sum(o['stall'] is not None for o in rs)}/{len(rs)}", end="")
    print()
    ot = [o["r"]["overtime"] for o in allo]
    hits = sum(sum(o["r"]["hits"]) for o in allo); oth = sum(o["r"]["overtime_hits"] for o in allo)
    print(f"rule fired: overtime reached in {sum(x > 0 for x in ot)}/{n} = {pct(sum(x > 0 for x in ot), n)} of rounds,"
          f" {sum(ot)/n:.1f} overtime ticks per round | autopilot share {oth}/{hits} = {pct(oth, hits)} of hits")
    print(f"pit falls: {sum(sum(o['r']['falls']) for o in allo)} in all, {sum(o['ot_falls'] for o in allo)} in overtime"
          f" | rebuilt overtime count matches play() in {sum(o['ot_check'] for o in allo)}/{n}")
    at = sum(o["att_ticks"] for o in allo)
    if at:
        br, bf = sum(o["blk_right"] for o in allo), sum(o["blk_fwd"] for o in allo)
        print(f"C's second half (IF_BLOCKED RIGHT ELSE FWD): {br + bf}/{at} = {pct(br + bf, at)} of attacker overtime ticks"
              f" (RIGHT when blocked {br}, Otherwise FWD {bf})")
    stuck = [(b, k, o) for (b, k, o) in rows if o["stall"]]
    if stuck:
        c = Counter(o["stall"]["cause"] for b, k, o in stuck); pk = sum(o["stall"]["parked"] for b, k, o in stuck)
        wh = [o.get("where") for b, k, o in stuck if o.get("where")]
        print(f"stuck stretches ({len(stuck)}): apart {c['apart']}, dance {c['dance']}, parked {pk}"
              f" | attacker on/next to an inner pocket for >= half the stretch {sum(x['near'] for x in wh)}/{len(wh)},"
              f" ever {sum(x['any'] for x in wh)}/{len(wh)}")
        for b, k, o in stuck[:6]:
            x = o.get("where") or {}
            print(f"   {b} [{k}] {o['progs'][0]}  vs  {o['progs'][1]}  [{o['stall']['cause']}] attacker seat {x.get('att')},"
                  f" {x.get('squares')} squares, last: {x.get('path')}")

def mirror_trace(vk, prog="IF_HIT HUNT IF_ENEMY FIRE", board="Pillars and pits"):
    walls, pits = LAYOUTS[board]
    arrows = "NESW"
    for first in (0, 1):
        cfg = make_cfg(vk, walls, pits, first); p = parse(prog)
        tr = []; r = play(p, p, cfg, trace=tr); st = E7.stall_info(tr, cfg.shot_clock)
        print(f"\n[{vk}] mirror `{prog}` on {board}, clock_first={first}: winner {r['winner']}, armor {r['armor']},"
              f" overtime {r['overtime']} ticks, {'STUCK ' + st['cause'] if st else 'not stuck'}")
        if first == 0 or st:
            w = cfg.size + 2; xy = lambda q: (q % w - 1, q // w - 1)
            ot = overtime_ticks(tr, cfg.shot_clock, cfg.armor)
            nm = lambda a: NAMES[a] if a >= 0 else "IDLE"
            for i, row in enumerate(tr):
                if not ot[i] or i > 34: continue
                print(f"   t{row[0]:2d} A{xy(row[3])}{arrows[row[4]]} {nm(row[1]):<6} {row[5]} | B{xy(row[6])}{arrows[row[7]]} {nm(row[2]):<6} {row[8]}")

