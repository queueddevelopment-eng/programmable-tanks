def draw(walls, pits, size=SIZE):
    """ASCII board, north up: # wall, o pit, * inner pocket, + edge pocket."""
    inner, edge = pockets(walls, pits, size)
    rows = []
    for y in range(size - 1, -1, -1):
        rows.append("".join("#" if (x, y) in walls else "o" if (x, y) in pits else "*" if (x, y) in inner
                            else "+" if (x, y) in edge else "." for x in range(size)))
    return rows

