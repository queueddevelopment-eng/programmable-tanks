"""
experiments8.py - E2: stalls under card-language overtime (the v0.5 rule, decision (m)).

Question: with the v0.5 shot clock (10 quiet ticks, the LEADER attacks, overtime written in the card language:
attacker `IF_ENEMY FIRE ELSE HUNT`, holder `IF_ENEMY FIRE ELSE TRACK`), how often does a round still stall,
and is a stall explained by "pockets" on the layout?
October's ~4% stuck (results/results7b.txt, variant F) had the TRAILER attacking with greedy Hunt; v0.5 was never measured.

Variants (brief from game-designer, 2026-11-24):
  | | Variant                | Config                                                                                  |
  |-|------------------------|-----------------------------------------------------------------------------------------|
  |A| v5 control             | shot_clock=10, clock_roles, clock_leader, clock_cards, clock_first=seed%2               |
  |B| pathfinding comparison | as A, but clock_cards=False, clock_path=True                                            |
  |C| 8-card attacker        | as A, clock_attack="IF_ENEMY FIRE ELSE HUNT IF_BLOCKED RIGHT ELSE FWD"                  |
  All: cooldown 1, Raise wall behind, Hunt avoids walls and pits, v0.4 deck + rare specials, pickups off,
  pit stops before ticks 11 and 21 (experiments5.STOPS), initiative off.

Layouts: the 5 named boards of experiments7.BOARDS, plus 12 generated by gen_deck() (fixed seed GEN_SEED):
  rotationally symmetric (a), start corners free, every free square connected; 6 with inner pockets, 6 without.
  A POCKET is a free square whose two orthogonal neighbours in perpendicular directions (they touch diagonally)
  are both blocked. Inner pocket: both blockers are walls or pits. Edge pocket: one blocker is the board edge
  (the four board corners are not counted). See pockets().

Proxies: experiments5 experts and novices, pairings cycling EvE, EvN, NvN, EvE, NvE, NvN.
Pairing: the seed is a function of (layout index, round index) only. Each job deals and BUILDS the two programs
ONCE (under variant A's rules) and then plays every requested variant from the same programs, hands and pile;
pit-stop choices run under each variant's own rules with a fresh RNG from the same seed. So variants differ
only in the overtime rule (and in pit-stop choices that the rule changes).

Metrics: stuck (experiments7.stall_info: the round ends with >= clock+10 = 20 ticks without an armor change,
nobody destroyed; pit damage counts), kills, draws, seat fairness (tank A wins / decided EvE+NvN rounds),
autopilot share (overtime hits / all hits). Rule-fired checks: rounds reaching overtime, overtime ticks per
round, rounds where A and C differ, C's IF_BLOCKED half, pit falls in overtime, stuck stretches with the attacker
on or next to an inner pocket, and a trace of the `IF_HIT HUNT IF_ENEMY FIRE` mirror on Pillars and pits.

Pass line (fixed before the run, 2026-11-24):
  - stuck <= 2% on every deck layout;
  - seat fairness 45-55%, pooled over EvE and NvN decided rounds;
  - variant C only: autopilot share within A's + 10 points.
  At 30 rounds a layout is only FLAGGED (>= 2 stuck), not passed or failed.

Usage: python experiments8.py <rounds_per_layout> <variants> [<variants>:named|gen ...]
  python experiments8.py 4 ABC                 # smoke
  python experiments8.py 30 AC B:named         # screen: A, C on 17 layouts, B on the 5 named boards
"""
