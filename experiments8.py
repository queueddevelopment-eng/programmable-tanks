def pockets(walls, pits, size=SIZE):
    """Pocket squares: free squares with two perpendicular orthogonal neighbours blocked.
    Returns (inner, edge): inner = both blockers are walls/pits; edge = one blocker is the board edge
    (the four corners, blocked only by two edges, are left out)."""
    block = set(walls) | set(pits)
    inner, edge = [], []
    dirs = ((0, 1), (1, 0), (0, -1), (-1, 0))
    for x in range(size):
        for y in range(size):
            if (x, y) in block: continue
            kinds = []
            for d in range(4):
                nx, ny = x + dirs[d][0], y + dirs[d][1]
                kinds.append("edge" if not (0 <= nx < size and 0 <= ny < size) else "blk" if (nx, ny) in block else None)
            pairs = [(kinds[d], kinds[(d + 1) % 4]) for d in range(4) if kinds[d] and kinds[(d + 1) % 4]]
            if any(p == ("blk", "blk") for p in pairs): inner.append((x, y))
            elif any("blk" in p for p in pairs): edge.append((x, y))
    return inner, edge

def connected(walls, pits, size=SIZE):
    """Both start corners free and every free square reachable from (0, 0) without crossing a wall or pit."""
    block = set(walls) | set(pits)
    if (0, 0) in block or (size - 1, size - 1) in block: return False
    seen, dq = {(0, 0)}, deque([(0, 0)])
    while dq:
        x, y = dq.popleft()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < size and 0 <= ny < size and (nx, ny) not in block and (nx, ny) not in seen:
                seen.add((nx, ny)); dq.append((nx, ny))
    return len(seen) == size * size - len(block)

def gen_layout(rng, size=SIZE):
    """One rotationally symmetric layout: 2-5 wall pairs and 0-2 pit pairs, start corners and their
    neighbours kept free, every free square connected. Returns (walls, pits)."""
    while True:
        nw, npit = rng.randint(2, 5), rng.randint(0, 2)
        walls, pits = set(), set()
        for target, n in ((walls, nw), (pits, npit)):
            while len(target) < 2 * n:
                x, y = rng.randrange(size), rng.randrange(size)
                if x + y <= 1 or x + y >= 2 * size - 3: continue
                m = (size - 1 - x, size - 1 - y)
                if (x, y) in walls or (x, y) in pits or m in walls or m in pits: continue
                target.add((x, y)); target.add(m)
        if connected(walls, pits, size): return tuple(sorted(walls)), tuple(sorted(pits))

def gen_deck(seed=GEN_SEED, each=6):
    """`each` generated layouts with inner pockets and `each` without, in generation order."""
    rng = random.Random(seed); yes, no = [], []
    while len(yes) < each or len(no) < each:
        w, p = gen_layout(rng)
        (yes if pockets(w, p)[0] else no).append((w, p))
    return yes[:each] + no[:each]

